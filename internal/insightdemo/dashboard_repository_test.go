package insightdemo

import (
	"context"
	"testing"
	"time"
)

func TestNewDashboardRepositoryBuildsFreshSeed(t *testing.T) {
	before := time.Now().Add(-2 * time.Minute)
	repo := NewDashboardRepository()
	after := time.Now().Add(2 * time.Minute)

	payload, err := repo.GetDashboard(context.Background(), "")
	if err != nil {
		t.Fatalf("expected nil error, got %v", err)
	}

	if payload.GeneratedAt.Before(before) || payload.GeneratedAt.After(after) {
		t.Fatalf("expected generatedAt near now, got %s", payload.GeneratedAt.Format(time.RFC3339))
	}
	if payload.Overview.ReportFreshness != "刚刚" {
		t.Fatalf("expected report freshness to be 刚刚, got %q", payload.Overview.ReportFreshness)
	}
	if payload.ReportSummary.AutoGeneratedAt != "刚刚" {
		t.Fatalf("expected auto generated at to be 刚刚, got %q", payload.ReportSummary.AutoGeneratedAt)
	}
	if payload.ReportSummary.GeneratedAt.Before(before) || payload.ReportSummary.GeneratedAt.After(after) {
		t.Fatalf("expected report summary generatedAt near now, got %s", payload.ReportSummary.GeneratedAt.Format(time.RFC3339))
	}
	expectedPeriod := payload.GeneratedAt.Format("2006-01-02") + " 日报"
	if payload.ReportSummary.Period != expectedPeriod {
		t.Fatalf("expected period %q, got %q", expectedPeriod, payload.ReportSummary.Period)
	}
	if len(payload.HotVideos) == 0 || payload.HotVideos[0].Source != "wx_feed_list" || payload.HotVideos[0].PublishedAt.IsZero() {
		t.Fatalf("expected seeded hot video trace fields, got %+v", payload.HotVideos)
	}
	if len(payload.HotTopics) == 0 || payload.HotTopics[0].Source != "wx_comment_export" || payload.HotTopics[0].ObservedAt.IsZero() || len(payload.HotTopics[0].SourceAccounts) == 0 {
		t.Fatalf("expected seeded hot topic trace fields, got %+v", payload.HotTopics)
	}
}
