package insightfile_test

import (
	"context"
	"path/filepath"
	"testing"
	"time"

	"github.com/nobiyou/wx_channel_insight/internal/insight"
	"github.com/nobiyou/wx_channel_insight/internal/insightfile"
)

func TestReportSummaryRepositoryPersistsByWorkspace(t *testing.T) {
	storePath := filepath.Join(t.TempDir(), "report-summary.json")
	seed := insight.ReportSummary{
		Period:            "2026-07-03 日报",
		Headline:          "seed",
		KeyFinding:        "seed",
		RecommendedAction: "seed",
		Watchout:          "seed",
		AutoGeneratedAt:   "刚刚",
	}
	repo, err := insightfile.NewReportSummaryRepository(storePath, seed)
	if err != nil {
		t.Fatalf("new repository failed: %v", err)
	}

	alpha := insight.ReportSummary{
		Period:            "2026-07-04 日报",
		Headline:          "alpha",
		KeyFinding:        "alpha",
		RecommendedAction: "alpha",
		Watchout:          "alpha",
		AutoGeneratedAt:   "刚刚",
	}
	if err := repo.ReplaceReportSummary(context.Background(), "ws-alpha", alpha); err != nil {
		t.Fatalf("replace alpha failed: %v", err)
	}

	reloaded, err := insightfile.NewReportSummaryRepository(storePath, seed)
	if err != nil {
		t.Fatalf("reload repository failed: %v", err)
	}
	got, found, err := reloaded.GetReportSummary(context.Background(), "ws-alpha")
	if err != nil {
		t.Fatalf("get alpha failed: %v", err)
	}
	if !found || got.Headline != "alpha" {
		t.Fatalf("expected alpha summary, got found=%t summary=%+v", found, got)
	}

	meta := insight.ReadModelArtifactMeta{
		LatestBatchID:  "batch-alpha",
		MaterializedAt: time.Date(2026, 7, 3, 10, 14, 0, 0, time.FixedZone("CST", 8*3600)),
	}
	if err := reloaded.ReplaceReportSummaryMeta(context.Background(), "ws-alpha", meta); err != nil {
		t.Fatalf("replace report summary meta failed: %v", err)
	}
	verified, err := insightfile.NewReportSummaryRepository(storePath, seed)
	if err != nil {
		t.Fatalf("verify repository reload failed: %v", err)
	}
	gotMeta, found, err := verified.GetMeta(context.Background(), "ws-alpha")
	if err != nil {
		t.Fatalf("get report meta failed: %v", err)
	}
	if !found || gotMeta.LatestBatchID != "batch-alpha" {
		t.Fatalf("expected persisted report meta, got found=%t meta=%+v", found, gotMeta)
	}
}

func TestReportSummaryRepositoryRefreshesAcrossLiveInstances(t *testing.T) {
	storePath := filepath.Join(t.TempDir(), "report-summary.json")
	seed := insight.ReportSummary{
		Period:            "2026-07-03 日报",
		Headline:          "seed",
		KeyFinding:        "seed",
		RecommendedAction: "seed",
		Watchout:          "seed",
		AutoGeneratedAt:   "刚刚",
	}

	writer, err := insightfile.NewReportSummaryRepository(storePath, seed)
	if err != nil {
		t.Fatalf("new writer repository failed: %v", err)
	}
	reader, err := insightfile.NewReportSummaryRepository(storePath, seed)
	if err != nil {
		t.Fatalf("new reader repository failed: %v", err)
	}

	updated := insight.ReportSummary{
		Period:            "2026-07-04 日报",
		Headline:          "beta",
		KeyFinding:        "beta finding",
		RecommendedAction: "beta action",
		Watchout:          "beta watchout",
		AutoGeneratedAt:   "刚刚",
	}
	if err := writer.ReplaceReportSummary(context.Background(), "ws-beta", updated); err != nil {
		t.Fatalf("replace beta failed: %v", err)
	}

	got, found, err := reader.GetReportSummary(context.Background(), "ws-beta")
	if err != nil {
		t.Fatalf("get beta failed: %v", err)
	}
	if !found || got.Headline != "beta" {
		t.Fatalf("expected live report summary refresh, got found=%t summary=%+v", found, got)
	}
}
