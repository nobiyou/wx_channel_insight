package insightfile_test

import (
	"context"
	"path/filepath"
	"testing"
	"time"

	"github.com/nobiyou/wx_channel_insight/internal/insight"
	"github.com/nobiyou/wx_channel_insight/internal/insightfile"
)

func TestDashboardRepositoryResetRestoresSeed(t *testing.T) {
	storePath := filepath.Join(t.TempDir(), "dashboard-snapshot.json")
	seed := insight.Dashboard{
		GeneratedAt: time.Date(2026, 6, 30, 17, 0, 0, 0, time.FixedZone("CST", 8*3600)),
		Workspace: insight.WorkspaceSummary{
			Name: "默认运营工作区",
		},
		Overview: insight.OverviewMetrics{
			MonitoredAccounts: 18,
			ReportFreshness:   "8 分钟前",
		},
		HotVideos:       []insight.HotVideo{{ID: "seed-video"}},
		HotTopics:       []insight.HotTopic{{ID: "seed-topic"}},
		WatchlistAlerts: []insight.WatchlistAlert{{ID: "seed-alert"}},
		CommentInsights: []insight.CommentInsight{{ID: "seed-comment"}},
		ReportSummary: insight.ReportSummary{
			Period:            "2026-06-30",
			Headline:          "H",
			KeyFinding:        "K",
			RecommendedAction: "R",
			Watchout:          "W",
			AutoGeneratedAt:   "今天",
		},
	}

	repo, err := insightfile.NewDashboardRepository(storePath, seed)
	if err != nil {
		t.Fatalf("expected nil error, got %v", err)
	}

	next := seed
	next.GeneratedAt = time.Date(2026, 6, 30, 18, 0, 0, 0, time.FixedZone("CST", 8*3600))
	next.Overview.MonitoredAccounts = 27
	if err := repo.ReplaceDashboard(context.Background(), "", next); err != nil {
		t.Fatalf("expected replace success, got %v", err)
	}

	if err := repo.ResetDashboard(context.Background(), ""); err != nil {
		t.Fatalf("expected reset success, got %v", err)
	}

	got, err := repo.GetDashboard(context.Background(), "")
	if err != nil {
		t.Fatalf("expected get success, got %v", err)
	}
	if got.GeneratedAt.Format(time.RFC3339) != "2026-06-30T17:00:00+08:00" {
		t.Fatalf("expected reset generatedAt, got %s", got.GeneratedAt.Format(time.RFC3339))
	}
	if got.Overview.MonitoredAccounts != 18 {
		t.Fatalf("expected reset monitored accounts 18, got %d", got.Overview.MonitoredAccounts)
	}
}
