func TestReadModelServiceLoadsReportSummaryFromDedicatedRepository(t *testing.T) {
	dashboardRepo := insightdemo.NewDashboardRepository()
	reportRepo := insightdemo.NewReportSummaryRepository(insight.ReportSummary{
		Period:            "2026-07-03 日报",
		Headline:          "seed",
		KeyFinding:        "seed",
		RecommendedAction: "seed",
		Watchout:          "seed",
		AutoGeneratedAt:   "刚刚",
	})
	contextResolver := workspace.NewContextResolver(
		workspace.NewDefaultWorkspaceService(workspacedemo.NewDefaultWorkspaceRepository()),
		workspace.ContextResolverConfig{
			DefaultHubUserID:   "hub:user:demo",
			DefaultDeviceCount: 2,
		},
	)
	service := insight.NewDashboardService(dashboardRepo, insight.DashboardServiceConfig{
		WorkspaceContextResolver: contextResolver,
		ReportSummaryRepository:  reportRepo,
	})
	if err := reportRepo.ReplaceReportSummary(context.Background(), "ws-default-hub-user-alice", insight.ReportSummary{
		Period:            "2026-07-04 日报",
		Headline:          "独立读模型日报",
		KeyFinding:        "今日重点",
		RecommendedAction: "跟进",
		Watchout:          "注意",
		AutoGeneratedAt:   "刚刚",
	}); err != nil {
		t.Fatalf("replace report summary failed: %v", err)
	}

	readService := insight.NewReadModelService(
		service,
		insight.WithReportSummaryRepository(reportRepo),
		insight.WithWorkspaceContextResolver(contextResolver),
	)

	got, err := readService.GetReportSummary(context.Background(), insight.DashboardQuery{
		HubUserID:     "hub:user:alice",
		DeviceCount:   2,
		ContextSource: "jobs",
	})
	if err != nil {
		t.Fatalf("get report summary failed: %v", err)
	}
	if got.Headline != "独立读模型日报" {
		t.Fatalf("expected dedicated summary, got %+v", got)
	}
}

func TestRefreshDashboardAlsoPersistsReportSummary(t *testing.T) {
	dashboardRepo := insightdemo.NewDashboardRepository()
	seed, err := dashboardRepo.GetDashboard(context.Background(), "")
	if err != nil {
		t.Fatalf("load seed failed: %v", err)
	}
	reportRepo := insightdemo.NewReportSummaryRepository(seed.ReportSummary)
	workspaceService := workspace.NewDefaultWorkspaceService(workspacedemo.NewDefaultWorkspaceRepository())
	contextResolver := workspace.NewContextResolver(workspaceService, workspace.ContextResolverConfig{
		DefaultHubUserID:   "hub:user:demo",
		DefaultDeviceCount: 2,
	})
	ingestRepo := ingestdemo.NewRepository()
	now := time.Date(2026, 7, 3, 10, 14, 0, 0, time.FixedZone("CST", 8*3600))
	ingestService := ingest.NewService(ingestRepo, ingest.ServiceConfig{
		DefaultHubUserID: "hub:user:demo",
		Now: func() time.Time { return now },
	})
	_, err = ingestService.ImportEvents(context.Background(), ingest.SummaryQuery{
		HubUserID:   "hub:user:alice",
		DeviceCount: 2,
	}, []ingest.Event{{
		ID:                    "comment-1",
		HubUserID:             "hub:user:alice",
		BatchID:               "batch-1",
		MachineID:             "machine-1",
		EventType:             "comment_snapshot",
		Source:                "wx_channel_comment_export",
		CollectedAt:           now,
		VideoCount:            1,
		CommentCount:          1,
		TopicCount:            1,
		Title:                 "团队运营版要怎么落地",
		ChannelName:           "Insight Test",
		Keyword:               "团队运营版",
		Cluster:               "执行规划",
		Signal:                "高追问",
		PromptAngle:           "先给运营台一个能每天看的主视图",
		RepresentativeComment: "先说说怎么落地",
		TargetAudience:        "运营负责人",
		Keywords:              []string{"团队运营版", "日报"},
	}})
	if err != nil {
		t.Fatalf("import events failed: %v", err)
	}

	refreshService := insight.NewReadModelRefreshService(insight.ReadModelRefreshServiceConfig{
		Repository:               dashboardRepo,
		ReportSummaryRepository:  reportRepo,
		WorkspaceContextResolver: contextResolver,
		IngestService:            ingestService,
		Materializer:             insight.NewMaterializer(seed),
	})

	payload, err := refreshService.RefreshDashboard(context.Background(), insight.DashboardQuery{
		HubUserID:     "hub:user:alice",
		DeviceCount:   2,
		ContextSource: "jobs",
	}, "jobs")
	if err != nil {
		t.Fatalf("refresh dashboard failed: %v", err)
	}

	got, found, err := reportRepo.GetReportSummary(context.Background(), "ws-default-hub-user-alice")
	if err != nil {
		t.Fatalf("get persisted summary failed: %v", err)
	}
	if !found {
		t.Fatalf("expected report summary to be persisted")
	}
	if got.Headline != payload.ReportSummary.Headline {
		t.Fatalf("expected persisted summary to match dashboard summary, got persisted=%+v payload=%+v", got, payload.ReportSummary)
	}
}
