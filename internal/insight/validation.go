package insight

import (
	"errors"
	"fmt"
)

var ErrInvalidDashboardSnapshot = errors.New("invalid dashboard snapshot")

type ValidationError struct {
	Field   string
	Message string
}

func (e *ValidationError) Error() string {
	if e.Field == "" {
		return fmt.Sprintf("%s: %s", ErrInvalidDashboardSnapshot, e.Message)
	}
	return fmt.Sprintf("%s: %s %s", ErrInvalidDashboardSnapshot, e.Field, e.Message)
}

func (e *ValidationError) Unwrap() error {
	return ErrInvalidDashboardSnapshot
}

func ValidateDashboardSnapshot(snapshot Dashboard) error {
	switch {
	case snapshot.GeneratedAt.IsZero():
		return &ValidationError{Field: "generatedAt", Message: "is required"}
	case snapshot.Workspace.Name == "":
		return &ValidationError{Field: "workspace.name", Message: "is required"}
	case snapshot.Overview.ReportFreshness == "":
		return &ValidationError{Field: "overview.reportFreshness", Message: "is required"}
	default:
		return ValidateReportSummary(snapshot.ReportSummary)
	}
}

func ValidateReportSummary(summary ReportSummary) error {
	switch {
	case summary.Period == "":
		return &ValidationError{Field: "reportSummary.period", Message: "is required"}
	case summary.Headline == "":
		return &ValidationError{Field: "reportSummary.headline", Message: "is required"}
	case summary.KeyFinding == "":
		return &ValidationError{Field: "reportSummary.keyFinding", Message: "is required"}
	case summary.RecommendedAction == "":
		return &ValidationError{Field: "reportSummary.recommendedAction", Message: "is required"}
	case summary.Watchout == "":
		return &ValidationError{Field: "reportSummary.watchout", Message: "is required"}
	case summary.AutoGeneratedAt == "":
		return &ValidationError{Field: "reportSummary.autoGeneratedAt", Message: "is required"}
	default:
		return nil
	}
}
