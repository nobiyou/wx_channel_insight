package insightpg_test

import (
	"context"
	"fmt"
	"testing"

	"github.com/nobiyou/wx_channel_insight/internal/insight"
	"github.com/nobiyou/wx_channel_insight/internal/insightpg"
	"github.com/nobiyou/wx_channel_insight/internal/postgres"
	"github.com/nobiyou/wx_channel_insight/internal/testpostgres"
)

func TestCurrentReadModelsRoundTripAndBoundDashboardProjection(t *testing.T) {
	db, _ := testpostgres.Open(t)
	client, err := postgres.NewClientFromDB(db, "postgres://test")
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	workspaceID := "ws-current-snapshot-pg"
	rankings, err := insightpg.NewRankingRepository(client)
	if err != nil {
		t.Fatal(err)
	}
	var videos []insight.HotVideo
	for index := 0; index < insight.DashboardPageHotVideoLimit+3; index++ {
		videos = append(videos, insight.HotVideo{ID: fmt.Sprintf("video-%d", index), Title: "current video"})
	}
	if err := rankings.ReplaceHotVideos(ctx, workspaceID, videos); err != nil {
		t.Fatal(err)
	}
	var topics []insight.HotTopic
	for index := 0; index < insight.DashboardPageHotTopicLimit+3; index++ {
		topics = append(topics, insight.HotTopic{ID: fmt.Sprintf("topic-%d", index), Keyword: fmt.Sprintf("current keyword %d", index)})
	}
	if err := rankings.ReplaceHotTopics(ctx, workspaceID, topics); err != nil {
		t.Fatal(err)
	}
	gotVideos, found, err := rankings.GetHotVideos(ctx, workspaceID)
	if err != nil || !found || len(gotVideos) != len(videos) {
		t.Fatalf("video read: found=%v count=%d err=%v", found, len(gotVideos), err)
	}
	pageVideos, pageRanks, videoFound, pageTopics, topicFound, err := rankings.GetDashboardPageRankings(ctx, workspaceID)
	if err != nil || !videoFound || !topicFound {
		t.Fatalf("dashboard projection: videos=%v topics=%v err=%v", videoFound, topicFound, err)
	}
	if len(pageVideos) != insight.DashboardPageHotVideoLimit || len(pageRanks[insight.HotVideoRankingHot]) != insight.DashboardPageHotVideoLimit || len(pageTopics) != insight.DashboardPageHotTopicLimit {
		t.Fatalf("projection limits: videos=%d rankings=%d topics=%d", len(pageVideos), len(pageRanks[insight.HotVideoRankingHot]), len(pageTopics))
	}
	comments, err := insightpg.NewCommentInsightRepository(client, nil)
	if err != nil {
		t.Fatal(err)
	}
	if err := comments.ReplaceCommentInsights(ctx, workspaceID, []insight.CommentInsight{{ID: "current-comment", Theme: "current theme"}}); err != nil {
		t.Fatal(err)
	}
	gotComments, found, err := comments.GetCommentInsights(ctx, workspaceID)
	if err != nil || !found || len(gotComments) != 1 || gotComments[0].ID != "current-comment" {
		t.Fatalf("comment read: found=%v items=%+v err=%v", found, gotComments, err)
	}
	summary := insight.ReportSummary{Period: "72h", Headline: "current report", KeyFinding: "current finding", RecommendedAction: "inspect current facts", Watchout: "check missing observations", AutoGeneratedAt: "now"}
	reports, err := insightpg.NewReportSummaryRepository(client, summary)
	if err != nil {
		t.Fatal(err)
	}
	if err := reports.ReplaceReportSummary(ctx, workspaceID, summary); err != nil {
		t.Fatal(err)
	}
	gotSummary, found, err := reports.GetReportSummary(ctx, workspaceID)
	if err != nil || !found || gotSummary.Headline != summary.Headline {
		t.Fatalf("report read: found=%v summary=%+v err=%v", found, gotSummary, err)
	}
}
