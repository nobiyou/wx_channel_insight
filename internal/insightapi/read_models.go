package insightapi

import "github.com/nobiyou/wx_channel_insight/internal/insight"

type HotVideosResponse struct {
	Ranking    string                       `json:"ranking"`
	Items      []HotVideoResponse           `json:"items"`
	ViewStatus *ReadModelViewStatusResponse `json:"viewStatus,omitempty"`
}

type HotTopicsResponse struct {
	Items      []HotTopicResponse           `json:"items"`
	ViewStatus *ReadModelViewStatusResponse `json:"viewStatus,omitempty"`
}

type CommentInsightsResponse struct {
	Items      []CommentInsightResponse     `json:"items"`
	ViewStatus *ReadModelViewStatusResponse `json:"viewStatus,omitempty"`
}

type ReportSummaryOnlyResponse struct {
	Item       ReportSummaryResponse        `json:"item"`
	ViewStatus *ReadModelViewStatusResponse `json:"viewStatus,omitempty"`
}

func NewHotVideosResponse(items []insight.HotVideo, viewStatus *insight.ReadModelViewStatus) HotVideosResponse {
	return NewRankedHotVideosResponse(items, insight.HotVideoRankingHot, viewStatus)
}

func NewRankedHotVideosResponse(items []insight.HotVideo, ranking string, viewStatus *insight.ReadModelViewStatus) HotVideosResponse {
	if normalized, ok := insight.NormalizeHotVideoRanking(ranking); ok {
		ranking = normalized
	} else {
		ranking = insight.HotVideoRankingHot
	}
	return HotVideosResponse{
		Ranking:    ranking,
		Items:      mapHotVideos(items),
		ViewStatus: mapOptionalReadModelViewStatus(viewStatus),
	}
}

func NewHotTopicsResponse(items []insight.HotTopic, viewStatus *insight.ReadModelViewStatus) HotTopicsResponse {
	return HotTopicsResponse{
		Items:      mapHotTopics(items),
		ViewStatus: mapOptionalReadModelViewStatus(viewStatus),
	}
}

func NewCommentInsightsResponse(items []insight.CommentInsight, viewStatus *insight.ReadModelViewStatus) CommentInsightsResponse {
	return CommentInsightsResponse{
		Items:      mapCommentInsights(items),
		ViewStatus: mapOptionalReadModelViewStatus(viewStatus),
	}
}

func NewReportSummaryOnlyResponse(item insight.ReportSummary, viewStatus *insight.ReadModelViewStatus) ReportSummaryOnlyResponse {
	return ReportSummaryOnlyResponse{
		Item: ReportSummaryResponse{
			Period:            item.Period,
			Headline:          item.Headline,
			KeyFinding:        item.KeyFinding,
			RecommendedAction: item.RecommendedAction,
			Watchout:          item.Watchout,
			AutoGeneratedAt:   item.AutoGeneratedAt,
		},
		ViewStatus: mapOptionalReadModelViewStatus(viewStatus),
	}
}

func mapOptionalReadModelViewStatus(item *insight.ReadModelViewStatus) *ReadModelViewStatusResponse {
	if item == nil {
		return nil
	}
	return &ReadModelViewStatusResponse{
		Key:            item.Key,
		Label:          item.Label,
		FreshnessState: item.FreshnessState,
		Summary:        item.Summary,
		SourceNote:     item.SourceNote,
		LatestBatchID:  item.LatestBatchID,
		MaterializedAt: formatTime(item.MaterializedAt),
	}
}
